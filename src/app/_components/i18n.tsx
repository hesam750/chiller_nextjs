 function nextDir(locale: Locale) {
   return locale === "en" ? "ltr" : "rtl";
 }
 
 type I18nValue = {
   locale: Locale;
   t: (key: string) => string;
   setLocale: (l: Locale) => void;
 };
 
 const I18nContext = createContext<I18nValue | null>(null);
 
 export function I18nProvider({ initialLocale, children }: { initialLocale: Locale; children: React.ReactNode }) {
   const [locale, setLocaleState] = useState<Locale>(initialLocale);
   const t = useMemo(() => {
     const d = dicts[locale] || {};
     return (key: string) => d[key] ?? key;
   }, [locale]);
   const setLocale = (l: Locale) => {
     setLocaleState(l);
     try {
       const maxAge = 365 * 24 * 60 * 60;
       document.cookie = `lang=${l}; path=/; max-age=${maxAge}`;
     } catch {}
     try {
       const el = document.documentElement;
       el.setAttribute("lang", l);
       el.setAttribute("dir", nextDir(l));
     } catch {}
   };
   useEffect(() => {
     try {
       const el = document.documentElement;
       el.setAttribute("lang", locale);
       el.setAttribute("dir", nextDir(locale));
     } catch {}
   }, [locale]);
   const value = useMemo(() => ({ locale, t, setLocale }), [locale, t]);
   return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
 }
 
 export function useI18n() {
   const ctx = useContext(I18nContext);
   if (!ctx) {
     throw new Error("I18nProvider missing");
   }
   return ctx;
 }
